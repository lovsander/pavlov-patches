/* Минимальный boot2-стадия для RP2040 (256 байт).
   Реальный bootrom проверяет CRC32 первых 252 байт флеша и прыгает на
   0x10000100. В симуляторе флеш уже отображена, поэтому от boot2 нужна только
   корректная контрольная сумма: одна ветка в приложение + паддинг 0xFF + CRC.
   Значение CRC подставляет embedded/build_pico.ps1 (двухпроходная сборка). */
#ifndef BOOT2_CRC
#define BOOT2_CRC 0
#endif

.syntax unified
.cpu cortex-m0plus
.thumb

.section .boot2, "ax"
    b 0x10000100            /* PC-относительная ветка на приложение */
    .space 250, 0xFF        /* до 252 байт: паддинг, как в стёртой флеш */
    .word BOOT2_CRC         /* CRC32 первых 252 байт, little-endian */
