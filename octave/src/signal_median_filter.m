function out = signal_median_filter(x, window)
% Медианный фильтр по КОЛЬЦУ (окно в точках).
%
% Векторизация: матрица индексов n×w строится один раз, медиана берётся по
% строкам. Цикл по точкам, как в R-порте, в Octave стоил бы секунды на сечение
% (6000 точек × окно 167), поэтому здесь «индексы матрицей».
  x = x(:);
  n = numel(x);
  w = signal_odd_window(window, n);
  if w < 3 || n < 3
    out = repmat(signal_median2(x), n, 1);
    return;
  end
  h = (w - 1) / 2;
  % Индекс окна для точки i: i−h … i+h (с заворотом). В 1-based это
  % mod(i − h − 1 + (0:w−1), n) + 1: «−1» здесь обязателен — без него окно
  % съезжает на точку вправо, а с ним и весь детектор (проверено вектором
  % vector_03: пик band уезжал на 2°, пока пятно не поправили в обоих фильтрах).
  idx = mod((1:n)' - h - 1 + (0:w - 1), n) + 1;
  out = median(x(idx), 2);
end
