function d = signal_circ_dist(a, b)
% Расстояние по кольцу (0..180°).
%
% ЛОВУШКА OCTAVE: rem() в Octave усекает к нулю (как C, rem(-1,360) == -1), а
% mod() округляет к минус бесконечности (mod(-1,360) == 359) — то есть ведёт
% себя как % в Python. Референс использует именно питоновскую семантику,
% поэтому везде mod, а не rem.
  d = abs(mod(a - b + 180, 360) - 180);
end
